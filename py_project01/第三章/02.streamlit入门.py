st.write("缅因猫最醒目的标签是“大”。成年公猫体重常在7~11公斤，母猫约5~7公斤，体长（含尾）可超过一米，骨架粗壮方正，胸部宽阔，脚掌大而带簇毛，如同一双天然的雪地靴。它的被毛长短不一、层次分明，颈部有围脖状的长毛，肩部毛短、腹部与后腿毛长，尾巴极其蓬松，形似浣熊尾——这也是它英文名中“Coon”的由来之一。头部轮廓硬朗，吻部呈方形，耳大且直立，耳尖往往带一撮猞猁般的聪明毛；眼睛大而略呈椭圆，颜色与被毛相配，常见绿色、金色与铜色。毛色几乎涵盖所有色系，其中虎斑最为经典，而带“M”形额纹的棕虎斑几乎成了这个品种的符号。")
st.write("与庞大身躯形成反差的是它出人意料的温和。缅因猫普遍亲人、稳定、耐性好，对陌生人不怯场，对孩子和其他宠物也多能和平相处。它不以尖细的喵叫表达诉求，而是发出一种轻柔的颤音、咕噜声，甚至像鸟鸣般的啁啾。它喜欢参与家庭活动，会跟着人从一个房间走到另一个房间，被形容为“猫中之狗”；不少个体还能学会衔回玩具、伸出爪子握手，对水也不像多数猫那样抗拒。它聪明、有分寸，不黏人到令人窒息，也不会冷淡到疏远，是那种“在你脚边安静待着，你一伸手它就靠过来”的陪伴型性格。")

